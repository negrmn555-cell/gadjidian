export const retrievalCases = subjects.flatMap(([title, inflected, alias]) => {
  const expected = `Учеба/${title}.md`;
  return [title, inflected, alias, expected].map(query => ({ query, expected }));
});

export async function createCorpus(root, count = 1000) {
  await mkdir(path.join(root, 'Учеба'), { recursive: true });
  await mkdir(path.join(root, 'Архив'), { recursive: true });
  for (const [title, , alias, text] of subjects) {
    await writeFile(path.join(root, 'Учеба', `${title}.md`),
      `---\ntitle: ${title}\naliases: [${JSON.stringify(alias)}]\ntags: [учеба]\n---\n# ${title}\n\n## Определение\n${text}\n\n## Пример\nПроверочный материал.\n`);
  }
  for (let i = subjects.length; i < count; i++) {
    await writeFile(path.join(root, 'Архив', `${i}.md`),
      `# Журнал наблюдений ${i}\n\n## Измерения\n${'Синтетическая запись о погоде и маршруте прогулки. '.repeat(30)}\n`);
  }
}
